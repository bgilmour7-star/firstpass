// Writes supabase/seed/drills.sql from content/drills/*.json, for pasting into the Supabase SQL editor.
// Inserts drills that aren't there yet; never overwrites a drill someone has already reviewed.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
const dir = new URL('../content/drills/', import.meta.url);
const q = (s) => "'" + s.replace(/'/g, "''") + "'";
const rows = readdirSync(dir).filter((f) => f.endsWith('.json')).sort().map((f) => {
  const d = JSON.parse(readFileSync(new URL(f, dir), 'utf8'));
  const { id, status, ...content } = d;
  return `  (${q(id)}, ${q(status)}, ${q(JSON.stringify({ ...content, id }))}::jsonb)`;
});
writeFileSync(new URL('../supabase/seed/drills.sql', import.meta.url),
  `-- Generated by scripts/seed-sql.mjs from content/drills. Paste into the Supabase SQL editor.\n` +
  `insert into public.drills (id, status, content) values\n${rows.join(',\n')}\non conflict (id) do nothing;\n`);
console.log(`${rows.length} drills -> supabase/seed/drills.sql`);

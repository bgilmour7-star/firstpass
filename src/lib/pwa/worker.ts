// The service worker for the installed app (decision 0021), as a string so its version can carry the
// deploy's commit: a new deploy is a new worker, which is how the app knows to offer "Reload".
//
// What it does, and nothing more:
// - Today (/today, page loads only) comes from the network when there's signal; the latest copy is saved
//   with the time it was saved. With no signal, the saved copy opens.
// - The app's own files (/_next/static, /icons) are saved on first use. Their names change every deploy,
//   so old ones are dropped when a new version takes over.
// - Any other coach page with no signal shows /offline.html.
// - Never saved: sign-in, auth, admin, the API, parent links, join links, the landing page, privacy, and
//   anything that isn't a plain GET from this site.
// - It waits for the coach to press Reload before a new version takes over (never mid-practice).

export const WORKER_CACHE = { today: 'fp-today', files: 'fp-files', shell: 'fp-shell' } as const;

/** Paths the worker leaves entirely to the network. Exported for tests. */
export const NEVER = ['/login', '/auth/', '/admin', '/api/', '/p/', '/join/', '/email/', '/og/', '/privacy', '/account/password'];

export function workerSource(version: string): string {
  return `// Firstpass service worker ${version} (decision 0021). Generated by src/lib/pwa/worker.ts.
const VERSION = ${JSON.stringify(version)};
const TODAY = ${JSON.stringify(WORKER_CACHE.today)};
const FILES = ${JSON.stringify(WORKER_CACHE.files)};
const SHELL = ${JSON.stringify(WORKER_CACHE.shell)} + '-' + VERSION;
const NEVER = ${JSON.stringify(NEVER)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(SHELL).then((c) => c.addAll(['/offline.html', '/icons/icon-192.png'])));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.map((k) => {
      // A new version: drop the old shell and the old app files (their names changed anyway).
      if ((k.startsWith('fp-shell-') && k !== SHELL) || k === FILES) return caches.delete(k);
    }))).then(() => self.clients.claim())
  );
});

self.addEventListener('message', (event) => {
  if (event.data === 'reload') self.skipWaiting();
});

function never(path) {
  return path === '/' || NEVER.some((p) => path === p || path.startsWith(p.endsWith('/') ? p : p + '/') || path.startsWith(p + '?'));
}

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  const path = url.pathname;

  if (path.startsWith('/_next/static/') || path.startsWith('/icons/')) {
    event.respondWith(
      caches.open(FILES).then((c) => c.match(req).then((hit) => hit || fetch(req).then((res) => {
        if (res.ok) c.put(req, res.clone());
        return res;
      })))
    );
    return;
  }

  if (req.mode !== 'navigate' || never(path)) return;

  if (path === '/today') {
    event.respondWith(
      fetch(req).then((res) => {
        // A signed-out visit is redirected to sign-in: never save that.
        // Only the plain /today (today's practice) is saved; /today?plan=… is another day.
        if (res.ok && !res.redirected && res.type === 'basic' && !url.search) {
          const headers = new Headers(res.headers);
          headers.set('x-fp-saved-at', new Date().toISOString());
          res.clone().blob().then((body) => caches.open(TODAY).then((c) => c.put('/today', new Response(body, { status: 200, headers }))));
        }
        return res;
      }).catch(() => caches.open(TODAY).then((c) => c.match('/today')).then((hit) => hit || caches.match('/offline.html')))
    );
    return;
  }

  // Other coach pages: the network, or the offline page.
  event.respondWith(fetch(req).catch(() => caches.match('/offline.html').then((hit) => hit || Response.error())));
});
`;
}
